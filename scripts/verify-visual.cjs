const { app, BrowserWindow, ipcMain } = require('electron')
const path = require('path')
const fs = require('fs')
const os = require('os')
const assert = require('assert/strict')
const root = path.resolve(__dirname, '..')
const output = path.join(os.tmpdir(), 'oblyvium-launcher-qa')
const fixture = path.join(root, 'app', '.forja-qa.html')
const remoteMain = require('@electron/remote/main')
remoteMain.initialize()
fs.mkdirSync(output, { recursive: true })
const runProfile = path.join(output, 'runs', String(process.pid))
fs.mkdirSync(runProfile, { recursive: true })
process.env.APPDATA = path.join(runProfile, 'profile')
process.env.ELECTRON_IS_DEV = '1'
// Never let QA read the production notifications feed or changelog.
process.env.OBLYVIUM_NOTIFICATIONS_URL = 'http://127.0.0.1:9/notifications.json'
// A local changelog with notes for 9.9.9 only; every other version has none.
const changelogServer = require('http').createServer((_req, res) => {
    res.writeHead(200, { 'content-type': 'application/json' })
    res.end(JSON.stringify({ version: 1, generatedAt: new Date().toISOString(), releases: [
        { version: '9.9.9', title: 'Teste visual', notes: 'Resumo da versão.\n- Primeiro item\n- <b>Segundo</b> item', publishedAt: new Date().toISOString() }
    ] }))
})
app.setPath('userData', path.join(runProfile, 'userData'))
app.disableHardwareAcceleration()
const preload = path.join(output, 'preload.cjs')
fs.writeFileSync(preload, `
const root = ${JSON.stringify(root)};
const C = require(root + '/app/assets/js/configmanager');
C.load();
require(root + '/app/assets/js/langloader').setupLanguage();
const api = require(root + '/app/assets/js/distromanager').DistroAPI;
const {HeliosDistribution} = require(root + '/node_modules/helios-core/dist/common/distribution/DistributionFactory.js');
const raw = {version:'1.0.0', servers:[{id:'visual-qa',name:'Servidor de teste visual',description:'Dados isolados de verificação',icon:require('url').pathToFileURL(root+'/app/assets/images/oblyvium-mark.svg').href,address:'127.0.0.1:25565',minecraftVersion:'1.20.1',version:'1.0.0',mainServer:true,autoconnect:false,modules:[]}]};
api.rawDistribution = raw;
api.distribution = new HeliosDistribution(raw, C.getCommonDirectory(), C.getInstanceDirectory());
api.refreshDistributionOrFallback = async () => api.distribution;
C.setSelectedServer('visual-qa');
`)
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
const errors = []
let window
let microsoftRequested = false
ipcMain.on('MSFT_AUTH_OPEN_LOGIN', () => { microsoftRequested = true })

app.whenReady().then(async () => {
    await new Promise(resolve => changelogServer.listen(0, '127.0.0.1', resolve))
    process.env.OBLYVIUM_CHANGELOG_URL = `http://127.0.0.1:${changelogServer.address().port}/changelog.json`
    const ejs = require('ejs')
    const Lang = require('../app/assets/js/langloader')
    Lang.setupLanguage()
    fs.writeFileSync(fixture, await ejs.renderFile(path.join(root, 'app/app.ejs'), { bkid: 0, lang: Lang.queryEJS }))
    window = new BrowserWindow({ width: 1100, height: 700, frame: false, show: false, webPreferences: { nodeIntegration: true, contextIsolation: false, backgroundThrottling: false, preload } })
    remoteMain.enable(window.webContents)
    window.webContents.on('console-message', event => { if (event.level === 'error') { console.error('Renderer:', event.message); if (/Uncaught|SyntaxError|ReferenceError|TypeError/.test(event.message)) errors.push(event.message) } })
    window.webContents.on('preload-error', (_event, _preload, error) => console.error('Preload:', error))
    const run = code => window.webContents.executeJavaScript(code)
    const click = async selector => {
        const point = await run(`(() => { const e = document.querySelector(${JSON.stringify(selector)}); if(e.closest('.settingsTab')) e.scrollIntoView({block:'nearest'}); const r=e.getBoundingClientRect(); return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}; })()`)
        window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point })
        window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point })
        await pause(1100)
    }
    const screenshot = async name => {
        await run('document.fonts.ready')
        await window.webContents.capturePage()
        await pause(60)
        fs.writeFileSync(path.join(output, name + '.png'), (await window.webContents.capturePage()).toPNG())
    }
    const bounds = async label => {
        const overflow = await run(`Array.from(document.querySelectorAll('#main button, #main input, #main h1, #main h2, .settingsTabHeaderText, .realm-intro')).filter(e=>{if(e.closest('#newsContainer'))return false;const r=e.getBoundingClientRect();return r.width>0&&r.height>0&&getComputedStyle(e).visibility!=='hidden'&&(r.left< -1||r.right>innerWidth+1||(!e.closest('.settingsTab')&&(r.top<0||r.bottom>innerHeight+1)))}).map(e=>e.id||e.className)`)
        assert.deepEqual(overflow, [], label + ': controls outside viewport')
    }
    await window.loadFile(fixture)
    await run('$.fx.off = true')
    await run('syncModConfigurations(DistroAPI.distribution); ensureJavaSettings(DistroAPI.distribution); showMainUI(DistroAPI.distribution)')
    await pause(2300)
    // Begin each run at the welcome screen, even if the isolated profile exists.
    await run(`$('#main > div').hide(); $('#overlayContainer, #loadingContainer').hide(); $('#main').show(); currentView=VIEWS.welcome; $(currentView).show();`)
    await screenshot('welcome')
    await bounds('welcome')
    await click('#welcomeButton')
    assert.equal(await run('getCurrentView()'), '#loginOptionsContainer')
    await screenshot('login-options')
    await bounds('login options')
    assert.ok(await run(`(() => {const logo=document.querySelector('.auth-mark').getBoundingClientRect();const card=document.getElementById('loginOptionsContent').getBoundingClientRect();return Math.abs(logo.x+logo.width/2-card.x-card.width/2)<1&&getComputedStyle(document.querySelector('.loginOptionsMainContent')).textAlign==='center'})()`), 'login logo and text centered')
    await click('#loginOptionOffline')
    assert.equal(await run('getCurrentView()'), '#loginOfflineContainer')
    assert.equal(await run('document.activeElement.id'), 'loginOfflineUsername')
    await run(`loginOfflineUsername.value='a'; loginOfflineUsername.dispatchEvent(new Event('input',{bubbles:true}));`)
    assert.equal(await run('loginOfflineButton.disabled'), true)
    await run(`loginOfflineUsername.value='ForjaTester'; loginOfflineUsername.dispatchEvent(new Event('input',{bubbles:true}));`)
    assert.equal(await run('loginOfflineButton.disabled'), false)
    await screenshot('offline-login')
    await bounds('offline login')
    assert.ok(await run(`(() => {const card=document.querySelector('#loginOfflineContainer #loginContent').getBoundingClientRect();const logo=document.getElementById('loginOfflineImageSeal').getBoundingClientRect();return Math.abs(logo.x+logo.width/2-card.x-card.width/2)<1&&getComputedStyle(document.getElementById('loginOfflineForm')).textAlign==='center'})()`), 'offline modal centered')
    await click('#loginOfflineButton')
    await pause(1800)
    assert.equal(await run('getCurrentView()'), '#landingContainer')
    await screenshot('landing')
    await bounds('landing')
    assert.equal(await run(`document.getElementById('landingNewsNotice').hidden`), true)
    assert.equal(await run(`document.getElementById('server_selection_icon').hidden`), false)
    assert.equal(await run(`document.getElementById('server_selection_icon').naturalWidth > 0`), true)
    assert.ok(await run(`(() => {const toolbar=document.getElementById('settingsMediaButton').getBoundingClientRect();const profile=document.getElementById('user_content').getBoundingClientRect();const actions=document.querySelector('#lower > #center').getBoundingClientRect();return Math.abs(toolbar.y+toolbar.height/2-profile.y-profile.height/2)<2&&Math.abs(actions.x+actions.width/2-innerWidth/2)<2})()`), 'profile toolbar aligned and launch controls centered')
    assert.equal(await run(`document.querySelector('#lower #newsButton').getClientRects().length`), 0)
    // Any point of the profile frame (label, edges, chevron) must hit the select, or the click opens nothing.
    assert.deepEqual(await run(`(() => {const f=document.getElementById('profile_selection_wrap').getBoundingClientRect();return [[6,6],[20,14],[f.width-18,f.height/2],[20,f.height-4],[f.width-4,f.height-4]].map(([x,y])=>document.elementFromPoint(f.x+x,f.y+y)?.id)})()`), Array(5).fill('profile_selection'), 'whole profile frame opens the list')
    await run(`(async () => {const savedAjax=$.ajax; const raw=DistroAPI.distribution.rawDistribution; raw.rss='https://example.invalid/feed.xml'; try {$.ajax=options=>{options.success($.parseXML('<rss version="2.0"><channel><item><title>Notícia do RSS de teste visual</title><link>https://example.invalid/noticia</link><pubDate>Wed, 14 Oct 2026 12:00:00 GMT</pubDate><description><![CDATA[<p>Resumo fornecido pelo feed de teste, com conteúdo real do parser.</p>]]></description></item></channel></rss>'));return Promise.resolve()}; await initNews()} finally {$.ajax=savedAjax; delete raw.rss}})()`)
    assert.equal(await run(`document.getElementById('landingNewsNotice').hidden`), false)
    assert.equal(await run(`document.getElementById('landingNewsSummary').textContent`), 'Resumo fornecido pelo feed de teste, com conteúdo real do parser.')
    assert.equal(await run(`document.getElementById('landingNewsRead').href`), 'https://example.invalid/noticia')
    await screenshot('landing-rss')
    await run(`updateLandingNewsNotice({title:'Título longo do RSS para testar a composição. '.repeat(12),content:'Resumo longo da notícia de teste. '.repeat(20),link:'https://example.invalid/noticia'})`)
    await bounds('long RSS title')
    await screenshot('landing-rss-long')
    await run(`updateLandingNewsNotice({title:'Inválida',link:'javascript:alert(1)'})`)
    assert.equal(await run(`document.getElementById('landingNewsNotice').hidden`), true)
    await run(`updateSelectedServer(null)`)
    assert.equal(await run(`document.getElementById('server_selection_icon').hidden`), true)
    await run(`updateSelectedServer(DistroAPI.distribution.getMainServer())`)
    assert.equal(await run(`document.getElementById('launcherUpdateNotice').hidden`), true)
    await run(`showUpdateUI('downloading', {version:'9.9.9'}, 42.7)`)
    assert.equal(await run(`document.getElementById('launcherUpdateStatus').textContent`), 'Baixando a atualização... 42%')
    assert.equal(await run(`document.getElementById('launcherUpdateButton').hidden`), true)
    await run(`showUpdateUI('ready', {version:'9.9.9'})`)
    await bounds('update notice')
    await screenshot('landing-update')
    await run(`gameRunning = 1; document.getElementById('launcherUpdateButton').click()`)
    assert.equal(await run(`document.getElementById('launcherUpdateStatus').textContent`), 'Feche o jogo antes de atualizar.')
    assert.equal(await run(`document.getElementById('launcherUpdateButton').disabled`), false)
    await run(`gameRunning = 0; document.getElementById('launcherUpdateNotice').hidden = true`)
    await click('#settingsMediaButton')
    assert.equal(await run('getCurrentView()'), '#settingsContainer')
    for (const tab of ['Account', 'Minecraft', 'Launcher', 'About', 'Update']) {
        await click(`.settingsNavItem[rsc="settingsTab${tab}"]`)
        assert.equal(await run('selectedSettingsTab'), 'settingsTab' + tab)
        await bounds('settings ' + tab)
        await screenshot('settings-' + tab.toLowerCase())
        assert.equal(await run(`document.getElementById('settingsBackButton').getClientRects().length > 0`), true)
    }
    await run(`populateSettingsUpdateInformation({ version: '9.9.9' })`)
    for (let i = 0; i < 50 && !(await run(`document.querySelector('#settingsTabUpdate .settingsChangelogText').textContent.includes('Primeiro item')`)); i++) await pause(100)
    assert.equal(await run(`document.querySelector('#settingsTabUpdate .settingsChangelogTitle').textContent`), 'v9.9.9 · Teste visual')
    assert.deepEqual(await run(`[...document.querySelectorAll('#settingsTabUpdate .settingsChangelogText li')].map(li => li.textContent)`), ['Primeiro item', '<b>Segundo</b> item'])
    assert.equal(await run(`document.querySelector('#settingsTabUpdate .settingsChangelogText b')`), null, 'notes are text, never HTML')
    await screenshot('settings-update-changelog')
    await run(`populateSettingsUpdateInformation({ version: '1.2.3' })`)
    for (let i = 0; i < 50 && (await run(`document.querySelector('#settingsTabUpdate .settingsChangelogText').textContent.includes('Carregando')`)); i++) await pause(100)
    assert.equal(await run(`document.querySelector('#settingsTabUpdate .settingsChangelogText').textContent`), 'As novidades da versão 1.2.3 ainda não foram publicadas. Acompanhe no nosso Discord.')
    assert.equal(await run(`document.getElementById('settingsTabUpdate').textContent.includes('undefined')`), false)
    await run(`populateSettingsUpdateInformation(null)`)
    await click('.settingsNavItem[rsc="settingsTabMinecraft"]')
    const previous = await run(`document.querySelector('#settingsTabMinecraft .toggleSwitch input').checked`)
    await click('#settingsTabMinecraft .toggleSwitch input')
    assert.notEqual(await run(`document.querySelector('#settingsTabMinecraft .toggleSwitch input').checked`), previous)
    await click('#settingsNavDone')
    assert.equal(await run(`getCurrentView()`), '#landingContainer')
    await click('#settingsMediaButton')
    await click('#settingsBackButton')
    assert.equal(await run(`getCurrentView()`), '#landingContainer')
    await click('#settingsMediaButton')
    await run(`document.getElementById('settingsBackButton').focus()`)
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ESCAPE' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ESCAPE' })
    await pause(400)
    assert.equal(await run(`getCurrentView()`), '#landingContainer')
    await click('#server_selection_button')
    assert.equal(await run('isOverlayVisible()'), true)
    await screenshot('server-dialog')
    await click('#serverSelectCancel')
    assert.equal(await run('isOverlayVisible()'), false)
    await run(`window.qaConfirmCount=0; window.qaCancelCount=0; setOverlayHandler(()=>{window.qaConfirmCount++;toggleOverlay(false)}); setDismissHandler(()=>{window.qaCancelCount++;toggleOverlay(false)}); toggleOverlay(true,true);`)
    await pause(350)
    await run(`document.getElementById('overlayDismiss').focus()`)
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ENTER' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ENTER' })
    await pause(350)
    assert.equal(await run('window.qaCancelCount'), 1)
    assert.equal(await run('window.qaConfirmCount'), 0)
    await run(`toggleOverlay(true,true)`)
    await pause(350)
    await run(`document.getElementById('overlayAcknowledge').focus()`)
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ENTER' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ENTER' })
    await pause(350)
    assert.equal(await run('window.qaConfirmCount'), 1)
    await run(`setOverlayContent('Não foi possível preparar o jogo.', 'Verifique sua conexão e tente novamente.', 'Tentar novamente', 'Voltar'); setOverlayHandler(null); setDismissHandler(null); toggleOverlay(true,true);`)
    await pause(350)
    await screenshot('error-dialog')
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ESCAPE' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ESCAPE' })
    await pause(350)
    assert.equal(await run('isOverlayVisible()'), false)
    await run(`$('#launch_content').hide(); $('#launch_details').css('display','flex'); launch_progress.value=63; launch_progress_label.textContent='63%'; launch_details_text.textContent='Verificando arquivos do jogo…';`)
    await screenshot('progress')
    await bounds('progress')
    await run(`$('#launch_details').hide(); $('#launch_content').show();`)
    for (const [width, height] of [[800, 560], [390, 844]]) {
        window.setSize(width, height)
        await pause(250)
        await bounds('landing ' + width)
        await screenshot('landing-' + width)
    }
    window.setSize(1100, 700)
    await click('#settingsMediaButton')
    window.setSize(1920, 1080)
    await click('.settingsNavItem[rsc="settingsTabAccount"]')
    await screenshot('settings-account-wide')
    assert.equal(await run(`getComputedStyle(document.querySelector('.settingsAuthAccountLogOut')).opacity`), '1')
    await bounds('wide settings')
    window.setSize(800, 560)
    await pause(100)
    await bounds('compact settings')
    await screenshot('settings-account-800')
    window.setSize(1100, 700)
    await click('#settingsNavDone')
    await run(`$('#main > div').hide(); currentView=VIEWS.loginOptions; $(currentView).show();`)
    await click('#loginOptionMicrosoft')
    assert.equal(microsoftRequested, true)
    assert.equal(await run('getCurrentView()'), '#waitingContainer')
    await run('$.fx.off = false')
    window.webContents.send('MSFT_AUTH_REPLY_LOGIN', 'MSFT_AUTH_REPLY_ERROR', 'MSFT_AUTH_ERR_ALREADY_OPEN', '#settingsContainer')
    await pause(1250)
    assert.equal(await run('getCurrentView()'), '#settingsContainer')
    assert.equal(await run('isOverlayVisible()'), true)
    assert.equal(await run(`document.getElementById('overlayContainer').contains(document.activeElement)`), true)
    await screenshot('microsoft-error-focus')
    await run('$.fx.off = true')
    await click('#overlayAcknowledge')
    await run(`$('#main > div').hide(); currentView=VIEWS.waiting; $(currentView).show();`)
    await screenshot('waiting')
    await run(`$('#main > div').hide(); $('#loadingContainer').show();`)
    await screenshot('loading')
    assert.deepEqual(errors, [], 'renderer errors')
    console.log(JSON.stringify({ result: 'PASS', output, checks: ['EJS rendering', 'centered login modals and field focus', 'welcome → accounts → offline → landing', 'username validation', 'all five settings tabs', 'three settings exits', 'settings toggle', 'server dialog and selected icon', 'centered launch controls and aligned profile', 'whole profile frame opens the list', 'conditional RSS, description fallback and long titles', 'update notice: progress, restart button, blocked while the game runs', 'changelog from the API: notes as text, missing version message', 'Escape dialog and dropdown behavior', 'launch progress', '800px and 390px landing layouts', '800px and 1920px settings layouts', 'Microsoft login request and error-dialog focus', 'no renderer exceptions'], microsoftRequested }, null, 2))
    changelogServer.close()
    app.quit()
}).catch(error => { console.error(error); app.exit(1) })
app.on('quit', () => { if (fs.existsSync(fixture)) fs.unlinkSync(fixture) })
